def render_scripts() -> dict[str, str]:
    return {
        "sysinfo.py": SYSINFO_PY.lstrip("\n"),
        "media.py": MEDIA_PY.lstrip("\n"),
        "media-control.py": MEDIA_CONTROL_PY.lstrip("\n"),
        "workspaces.py": WORKSPACES_PY.lstrip("\n"),
        "switch-workspace.py": SWITCH_WORKSPACE_PY.lstrip("\n"),
    }


def dependency_report() -> dict[str, bool]:
    return {name: shutil.which(name) is not None for name in ("eww", "python3", "hyprctl", "playerctl")}


def _pid() -> int | None:
    try:
        value = int(PIDFILE.read_text().strip())
        return value if value > 1 else None
    except (OSError, ValueError):
        return None


def _matches_homepage(pid: int) -> bool:
    try:
        command = Path(f"/proc/{pid}/cmdline").read_bytes().replace(b"\0", b" ").decode(errors="replace")
    except OSError:
        return False
    if "eww" not in command:
        return False
    return "daemon" in command or str(EWW_DIR) in command


def is_running() -> bool:
    pid = _pid()
    if pid is None or not _matches_homepage(pid):
        _clean_pidfile()
        return _ping_daemon()
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        _clean_pidfile()
        return False


def _ping_daemon(env: dict | None = None) -> bool:
    try:
        result = subprocess.run(
            ["eww", "ping", "--config", str(EWW_DIR)],
            env=env or os.environ,
            capture_output=True, text=True, timeout=2, check=False,
        )
        return result.returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def _stale_socket_paths() -> list[Path]:
    """All eww server sockets that belong to this config directory."""
    try:
        entries = list(RUNTIME_DIR.iterdir())
    except OSError:
        return []
    return [entry for entry in entries
            if entry.name.startswith("eww-server_") and entry.is_socket()]


def _clean_stale_socket() -> None:
    """Remove a leftover eww socket when the daemon is not answering."""
    if _ping_daemon():
        return
    for sock in _stale_socket_paths():
        try:
            sock.unlink()
        except OSError:
            pass


def _find_daemon_pid() -> int | None:
    """Locate the running eww daemon PID for this config directory."""
    try:
        result = subprocess.run(
            ["pgrep", "-f", f"eww .*daemon.*{EWW_DIR}"],
            capture_output=True, text=True, timeout=2, check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    for token in result.stdout.split():
        if token.isdigit():
            pid = int(token)
            if _matches_homepage(pid):
                return pid
    return None


def _wait_for_daemon(env: dict, timeout: float = 3.0) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if _ping_daemon(env):
            return True
        time.sleep(0.05)
    return False


def start() -> str:
    if is_running():
        return "homepage already running"
    missing = [name for name in ("eww", "python3") if not dependency_report()[name]]
    if missing:
        return "missing required dependencies: " + ", ".join(missing)
    if not (EWW_DIR / "eww.yuck").is_file() or not (EWW_DIR / "eww.scss").is_file():
        return "homepage configuration has not been generated"
    _clean_pidfile()
    _clean_stale_socket()
    env = dict(os.environ)
    env.setdefault("XDG_RUNTIME_DIR", str(RUNTIME_DIR))
    env["GDK_BACKEND"] = "wayland"
    try:
        daemon = subprocess.Popen(
            ["eww", "daemon", "--force-wayland", "--no-daemonize", "--config", str(EWW_DIR)],
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
            start_new_session=True,
        )
        if not _wait_for_daemon(env):
            if daemon.poll() is not None:
                _, err = daemon.communicate(timeout=1)
                return "eww daemon failed to start: " + ((err or b"").decode(errors="replace").strip()
                                                        or "unknown error")
            return "eww daemon did not become ready in time"
        opened = subprocess.run(
            ["eww", "open", "homepage", "--force-wayland", "--config", str(EWW_DIR)],
            env=env, check=False, capture_output=True, text=True, timeout=5,
        )
        if opened.returncode:
            return "eww failed to open homepage: " + (opened.stderr.strip() or "unknown error")
        pid = _find_daemon_pid()
        if pid is None:
            return "homepage opened but its dedicated Eww process could not be verified"
        PIDFILE.parent.mkdir(parents=True, exist_ok=True)
        PIDFILE.write_text(f"{pid}\n")
        return "homepage started"
    except (OSError, subprocess.TimeoutExpired) as exc:
        return f"homepage start failed: {exc}"


def stop() -> str:
    pid = _pid()
    if pid is None:
        _clean_pidfile()
        return "homepage already stopped"
    if not _matches_homepage(pid):
        _clean_pidfile()
        return "removed stale homepage PID; no process was terminated"
    try:
        os.kill(pid, signal.SIGTERM)
        for _ in range(20):
            try:
                os.kill(pid, 0)
            except OSError:
                break
            time.sleep(0.05)
    except OSError:
        pass
    _clean_pidfile()
    return "homepage stopped"


def _clean_pidfile() -> None:
    try:
        PIDFILE.unlink()
    except OSError:
        pass
