def profile() -> dict:
    values = dict(DEFAULT)
    try:
        raw = json.loads(PROFILE_PATH.read_text())
    except (OSError, json.JSONDecodeError):
        return values
    if not isinstance(raw, dict):
        return values
    if isinstance(raw.get("enabled"), bool):
        values["enabled"] = raw["enabled"]
    if raw.get("alignment") in VALID_ALIGNMENTS:
        values["alignment"] = raw["alignment"]
    return values


def save(values: dict) -> None:
    out = dict(DEFAULT)
    out["enabled"] = bool(values.get("enabled", False))
    alignment = values.get("alignment", "left")
    if alignment not in VALID_ALIGNMENTS:
        raise ValueError(f"invalid homepage alignment: {alignment!r}")
    out["alignment"] = alignment
    PROFILE_PATH.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix="homepage.", suffix=".json", dir=PROFILE_PATH.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(out, handle, indent=2)
            handle.write("\n")
        os.replace(tmp, PROFILE_PATH)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _hex_to_rgba(hexcolor: str, alpha: float) -> str:
    value = hexcolor.lstrip("#")
    if len(value) != 6:
        raise ValueError(f"invalid color: {hexcolor!r}")
    red, green, blue = (int(value[index:index + 2], 16) for index in (0, 2, 4))
    return f"rgba({red}, {green}, {blue}, {alpha})"


