"""Desktop homepage overlay for Hyprland via Eww.

Generates Eww config (Yuck layout + SCSS theme) and manages the overlay
process lifecycle. The homepage is a transparent layer-shell surface
showing clock, theme info, workspaces, system stats, and media widgets.
"""

import json
import os
import signal
import subprocess
import tempfile

HOME = os.path.expanduser("~")
CFG = os.path.join(
    os.environ.get("XDG_CONFIG_HOME", HOME + "/.config"))
PROFILE_PATH = os.path.join(CFG, "theme-engine", "homepage.json")
EWW_DIR = os.path.join(CFG, "eww", "homepage")
PIDFILE = os.path.join(
    os.environ.get("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}"),
    "theme-homepage.pid")

DEFAULT = {
    "version": 1,
    "enabled": False,
    "alignment": "left",
}

VALID_ALIGNMENTS = ("left", "right")


def profile():
    values = dict(DEFAULT)
    try:
        with open(PROFILE_PATH) as f:
            raw = json.load(f)
    except (OSError, json.JSONDecodeError):
        return values
    if not isinstance(raw, dict):
        return values
    for key, default in DEFAULT.items():
        if key == "version":
            continue
        value = raw.get(key, default)
        if type(value) is type(default):
            values[key] = value
    return values


def save(values):
    out = {key: values.get(key, default) for key, default in DEFAULT.items()}
    directory = os.path.dirname(PROFILE_PATH)
    os.makedirs(directory, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix="homepage.", suffix=".json", dir=directory)
    try:
        with os.fdopen(fd, "w") as f:
            json.dump(out, f, indent=2)
            f.write("\n")
        os.replace(tmp, PROFILE_PATH)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _hex_to_rgba(hexcolor, alpha):
    """Convert '#RRGGBB' to 'rgba(R, G, B, alpha)'."""
    c = hexcolor.lstrip("#")
    r, g, b = int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16)
    return f"rgba({r}, {g}, {b}, {alpha})"


def _card_opacity(effects_preset):
    opacities = {
        "minimal": 0.85,
        "calm": 0.75,
        "polished": 0.70,
        "cyber": 0.60,
    }
    if effects_preset and effects_preset in opacities:
        return opacities[effects_preset]
    return 0.70


