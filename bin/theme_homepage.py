def _yuck_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def _wallpaper_path(theme_name: str) -> str:
    """Resolve the same wallpaper priority used by the main theme generator."""
    candidates = (
        CFG / "hypr" / "wallpapers" / f"{theme_name}.png",
        CFG / theme_name / "wallpaper.png",
        CFG / "hypr" / "wallpaper.png",
    )
    return str(next((candidate for candidate in candidates if candidate.is_file()), ""))


def _monitor_size() -> tuple[int, int]:
    """Return the logical size of Hyprland monitor 0."""
    try:
        result = subprocess.run(
            ["hyprctl", "monitors", "-j"],
            check=True,
            capture_output=True,
            text=True,
            timeout=2,
        )
        monitor = json.loads(result.stdout)[0]
        scale = float(monitor.get("scale", 1.0)) or 1.0
        width = max(1, round(int(monitor["width"]) / scale))
        height = max(1, round(int(monitor["height"]) / scale))
        if int(monitor.get("transform", 0)) in {1, 3, 5, 7}:
            width, height = height, width
        return width, height
    except (OSError, subprocess.SubprocessError, subprocess.TimeoutExpired,
            ValueError, KeyError, IndexError, TypeError, json.JSONDecodeError):
        return 1920, 1080


