SYSINFO_SCRIPT = r"""#!/usr/bin/env bash
# System info poller for the homepage overlay.
cpu=$(awk '/^cpu / {u=$2+$4; t=$2+$4+$5; if(t>0) printf "%.0f", u*100/t}' /proc/stat 2>/dev/null || echo "?")

mem_info=$(awk '/MemTotal/{t=$2} /MemAvailable/{a=$2} END{
  used=(t-a)/1048576; total=t/1048576;
  printf "%.1f/%.0fG", used, total
}' /proc/meminfo 2>/dev/null || echo "?")

disk=$(df -h / 2>/dev/null | awk 'NR==2{gsub(/%/,"",$5); print $5}' || echo "?")

uptime_sec=$(awk '{printf "%.0f", $1}' /proc/uptime 2>/dev/null || echo "0")
days=$((uptime_sec / 86400))
hours=$(( (uptime_sec % 86400) / 3600 ))
if [ "$days" -gt 0 ]; then
  up="${days}d ${hours}h"
else
  mins=$(( (uptime_sec % 3600) / 60 ))
  up="${hours}h ${mins}m"
fi

printf '{"cpu":"%s","mem":"%s","disk":"%s","uptime":"%s"}\n' "$cpu" "$mem_info" "$disk" "$up"
"""

MEDIA_SCRIPT = r"""#!/usr/bin/env bash
# Media info poller for the homepage overlay.
if ! command -v playerctl &>/dev/null; then
  echo '{"playing":false,"title":"","artist":""}'
  exit 0
fi

status=$(playerctl status 2>/dev/null || echo "Stopped")

if [ "$status" = "Playing" ] || [ "$status" = "Paused" ]; then
  title=$(playerctl metadata title 2>/dev/null || echo "")
  artist=$(playerctl metadata artist 2>/dev/null || echo "")
  printf '{"playing":true,"title":"%s","artist":"%s"}\n' \
    "$(echo "$title" | sed 's/"/\\"/g')" \
    "$(echo "$artist" | sed 's/"/\\"/g')"
else
  echo '{"playing":false,"title":"","artist":""}'
fi
"""

WORKSPACES_SCRIPT = r"""#!/usr/bin/env bash
# Workspace listener for the homepage overlay.
# Outputs JSON array of workspace IDs on each change.
get_workspaces() {
  if command -v hyprctl &>/dev/null; then
    hyprctl workspaces -j 2>/dev/null | jq -c '[.[].id] | sort' 2>/dev/null || echo "[1, 2, 3, 4, 5]"
  else
    echo "[1, 2, 3, 4, 5]"
  fi
}

# Initial output
get_workspaces

# Listen to Hyprland events for workspace changes
sock="$XDG_RUNTIME_DIR/hypr/$HYPRLAND_INSTANCE_SIGNATURE/.socket2.sock"
if [ -S "$sock" ]; then
  socat -u "UNIX-CONNECT:$sock" - 2>/dev/null | while read -r line; do
    case "$line" in
      workspace*|destroyworkspace*|createworkspace*)
        get_workspaces
        ;;
    esac
  done
else
  # No Hyprland socket — poll instead
  while true; do
    sleep 2
    get_workspaces
  done
fi
"""


def render_scripts():
    return {
        "sysinfo.sh": SYSINFO_SCRIPT.lstrip("\n"),
        "media.sh": MEDIA_SCRIPT.lstrip("\n"),
        "workspaces.sh": WORKSPACES_SCRIPT.lstrip("\n"),
    }


def is_running():
    try:
        pid = int(open(PIDFILE).read().strip())
        os.kill(pid, 0)
        return True
    except (OSError, ValueError):
        return False


def _get_pid():
    try:
        return int(open(PIDFILE).read().strip())
    except (OSError, ValueError):
        return None


def start():
    if is_running():
        return "homepage already running"
    _clean_pidfile()
    env = dict(os.environ)
    env.setdefault("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}")
    try:
        subprocess.run(
            ["eww", "daemon", "--config", EWW_DIR],
            env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        proc = subprocess.Popen(
            ["eww", "open", "homepage", "--config", EWW_DIR],
            env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        proc.wait(timeout=5)
        # Write eww daemon PID (find it by the config dir)
        result = subprocess.run(
            ["eww", "get", "clock-time", "--config", EWW_DIR],
            env=env, capture_output=True, text=True, timeout=5)
        # If eww responded, it's running — write a marker PID
        pid = os.getpid()
        try:
            pgrep = subprocess.run(
                ["pgrep", "-f", f"eww.*{EWW_DIR}"],
                capture_output=True, text=True, timeout=5)
            if pgrep.stdout.strip():
                pid = int(pgrep.stdout.strip().split()[0])
        except (OSError, subprocess.TimeoutExpired, ValueError):
            pass
        os.makedirs(os.path.dirname(PIDFILE), exist_ok=True)
        with open(PIDFILE, "w") as f:
            f.write(str(pid) + "\n")
        return "homepage started"
    except FileNotFoundError:
        return "eww not found — install with: sudo pacman -S eww"
    except subprocess.TimeoutExpired:
        return "eww timed out"


def stop():
    env = dict(os.environ)
    env.setdefault("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}")
    try:
        subprocess.run(
            ["eww", "close", "homepage", "--config", EWW_DIR],
            env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        subprocess.run(
            ["eww", "kill", "--config", EWW_DIR],
            env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except FileNotFoundError:
        pass
    _clean_pidfile()
    return "homepage stopped"


def _clean_pidfile():
    try:
        os.unlink(PIDFILE)
    except OSError:
        pass
