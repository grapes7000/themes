SYSINFO_PY = r'''#!/usr/bin/env python3
import json, os
from pathlib import Path

def cpu_sample():
    fields = [int(value) for value in Path("/proc/stat").read_text().splitlines()[0].split()[1:]]
    idle = fields[3] + (fields[4] if len(fields) > 4 else 0)
    return idle, sum(fields)

state = Path(os.environ.get("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}")) / "theme-homepage-cpu.json"
idle, total = cpu_sample()
cpu = "?"
try:
    previous = json.loads(state.read_text())
    delta_total = total - int(previous["total"])
    delta_idle = idle - int(previous["idle"])
    if delta_total > 0:
        cpu = str(round(100 * (delta_total - delta_idle) / delta_total))
except (OSError, ValueError, KeyError, TypeError, json.JSONDecodeError):
    pass
state.parent.mkdir(parents=True, exist_ok=True)
tmp = state.with_suffix(".tmp")
tmp.write_text(json.dumps({"idle": idle, "total": total}))
os.replace(tmp, state)
mem = {}
for line in Path("/proc/meminfo").read_text().splitlines():
    key, value = line.split(":", 1)
    mem[key] = int(value.split()[0])
used = (mem["MemTotal"] - mem.get("MemAvailable", mem.get("MemFree", 0))) / 1048576
total_gb = mem["MemTotal"] / 1048576
stat = os.statvfs("/")
disk = round(100 * (1 - stat.f_bavail / stat.f_blocks)) if stat.f_blocks else 0
seconds = int(float(Path("/proc/uptime").read_text().split()[0]))
days, remainder = divmod(seconds, 86400)
hours, remainder = divmod(remainder, 3600)
minutes = remainder // 60
uptime = f"{days}d {hours}h" if days else f"{hours}h {minutes}m"
print(json.dumps({"cpu": cpu, "mem": f"{used:.1f}/{total_gb:.0f}G", "disk": str(disk), "uptime": uptime}))
'''

MEDIA_PY = r'''#!/usr/bin/env python3
import json, shutil, subprocess

def run(*args):
    try:
        return subprocess.run(args, check=False, capture_output=True, text=True, timeout=2).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return ""

if not shutil.which("playerctl"):
    print(json.dumps({"visible": False, "status": "", "title": "", "artist": ""}))
    raise SystemExit
status = run("playerctl", "status")
visible = status in {"Playing", "Paused"}
print(json.dumps({
    "visible": visible,
    "status": "Now Playing" if status == "Playing" else ("Paused" if visible else ""),
    "title": run("playerctl", "metadata", "title") if visible else "",
    "artist": run("playerctl", "metadata", "artist") if visible else "",
}))
'''

WORKSPACES_PY = r'''#!/usr/bin/env python3
import json, shutil, subprocess
fallback = {"active": 1, "workspaces": [1, 2, 3, 4, 5]}
if not shutil.which("hyprctl"):
    print(json.dumps(fallback)); raise SystemExit
try:
    workspaces = json.loads(subprocess.run(["hyprctl", "workspaces", "-j"], check=True, capture_output=True, text=True, timeout=2).stdout)
    active = json.loads(subprocess.run(["hyprctl", "activeworkspace", "-j"], check=True, capture_output=True, text=True, timeout=2).stdout)
    ids = sorted({item["id"] for item in workspaces if isinstance(item.get("id"), int) and item["id"] > 0})
    print(json.dumps({"active": active.get("id", ids[0] if ids else 1), "workspaces": ids or fallback["workspaces"]}))
except (OSError, subprocess.SubprocessError, json.JSONDecodeError, KeyError, TypeError):
    print(json.dumps(fallback))
'''

SWITCH_WORKSPACE_PY = r'''#!/usr/bin/env python3
import re, shutil, subprocess, sys
value = sys.argv[1] if len(sys.argv) == 2 else ""
if not re.fullmatch(r"[1-9][0-9]*", value) or not shutil.which("hyprctl"):
    raise SystemExit(2)
raise SystemExit(subprocess.run(["hyprctl", "dispatch", "workspace", value], check=False).returncode)
'''


def render_scripts() -> dict[str, str]:
    return {
        "sysinfo.py": SYSINFO_PY.lstrip("\n"),
        "media.py": MEDIA_PY.lstrip("\n"),
        "workspaces.py": WORKSPACES_PY.lstrip("\n"),
        "switch-workspace.py": SWITCH_WORKSPACE_PY.lstrip("\n"),
    }


def dependency_report() -> dict[str, bool]:
    return {name: shutil.which(name) is not None for name in ("eww", "python3", "hyprctl", "playerctl")}


def _pid() -> int | None:
    try:
        value = int(PIDFILE.read_text().strip())
        return value if value > 1 else None
    except (OSError, ValueError):
        return None


def _matches_homepage(pid: int) -> bool:
    try:
        command = Path(f"/proc/{pid}/cmdline").read_bytes().replace(b"\0", b" ").decode(errors="replace")
    except OSError:
        return False
    return "eww" in command and str(EWW_DIR) in command


def is_running() -> bool:
    pid = _pid()
    if pid is None or not _matches_homepage(pid):
        _clean_pidfile()
        return False
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        _clean_pidfile()
        return False


def start() -> str:
    if is_running():
        return "homepage already running"
    missing = [name for name in ("eww", "python3") if not dependency_report()[name]]
    if missing:
        return "missing required dependencies: " + ", ".join(missing)
    if not (EWW_DIR / "eww.yuck").is_file() or not (EWW_DIR / "eww.scss").is_file():
        return "homepage configuration has not been generated"
    _clean_pidfile()
    env = dict(os.environ)
    env.setdefault("XDG_RUNTIME_DIR", str(RUNTIME_DIR))
    try:
        subprocess.run(["eww", "daemon", "--config", str(EWW_DIR)], env=env, check=False,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=5)
        opened = subprocess.run(["eww", "open", "homepage", "--config", str(EWW_DIR)], env=env,
                                check=False, capture_output=True, text=True, timeout=5)
        if opened.returncode:
            return "eww failed to open homepage: " + (opened.stderr.strip() or "unknown error")
        found = subprocess.run(["pgrep", "-f", f"eww.*--config {EWW_DIR}"], capture_output=True,
                               text=True, timeout=5, check=False)
        candidates = [int(value) for value in found.stdout.split() if value.isdigit()]
        pid = next((value for value in candidates if _matches_homepage(value)), None)
        if pid is None:
            return "homepage opened but its dedicated Eww process could not be verified"
        PIDFILE.parent.mkdir(parents=True, exist_ok=True)
        PIDFILE.write_text(f"{pid}\n")
        return "homepage started"
    except (OSError, subprocess.TimeoutExpired) as exc:
        return f"homepage start failed: {exc}"


def stop() -> str:
    pid = _pid()
    if pid is None:
        _clean_pidfile()
        return "homepage already stopped"
    if not _matches_homepage(pid):
        _clean_pidfile()
        return "removed stale homepage PID; no process was terminated"
    try:
        os.kill(pid, signal.SIGTERM)
        for _ in range(20):
            try:
                os.kill(pid, 0)
            except OSError:
                break
            time.sleep(0.05)
    except OSError:
        pass
    _clean_pidfile()
    return "homepage stopped"


def _clean_pidfile() -> None:
    try:
        PIDFILE.unlink()
    except OSError:
        pass
