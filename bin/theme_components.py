CFG = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))


def h(color: str) -> str:
    return color.lstrip("#")


def alpha_byte(value: float) -> str:
    return f"{max(0, min(255, round(float(value) * 255))):02x}"


def rgba(color: str, opacity: float = 1.0) -> str:
    return f"rgba({h(color)}{alpha_byte(opacity)})"


def atomic_text(path: Path, text: str, mode: int | None = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(f".{path.name}.theme-studio.tmp")
    temp.write_text(text, encoding="utf-8")
    os.replace(temp, path)
    if mode is not None:
        path.chmod(mode)


def replace_managed_block(
    path: Path, marker: str, content: str, prefix: str = "#"
) -> None:
    start = f"{prefix} THEME-STUDIO-{marker}-START"
    end = f"{prefix} THEME-STUDIO-{marker}-END"
    block = f"{start}\n{content.rstrip()}\n{end}\n"
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end) + r"\n?", re.DOTALL)
    if pattern.search(old):
        new = pattern.sub(block, old)
    else:
        new = old.rstrip() + ("\n\n" if old.strip() else "") + block
    atomic_text(path, new)


@dataclass(frozen=True)
class ComponentPlugin:
    name: str
    label: str
    renderer: Callable[[dict[str, Any]], list[Path]]
    description: str


PLUGINS: dict[str, ComponentPlugin] = {}


def register(name: str, label: str, description: str):
    def decorator(func: Callable[[dict[str, Any]], list[Path]]):
        PLUGINS[name] = ComponentPlugin(name, label, func, description)
        return func

    return decorator


def render_hypr(theme: dict[str, Any]) -> str:
    theme = ensure_theme_schema(theme)
    r = theme["roles"]
    w = theme["components"]["windows"]
    blur = w["blur"]
    shadow = w["shadow"]
    active = w["active_border"]
    inactive = w["inactive_border"]
    groups = w.get("group_border", {})
    active_1 = role_color(theme, str(active.get("color", "focus")))
    active_2 = role_color(theme, str(active.get("color_2", "accent2")))
    inactive_color = role_color(theme, str(inactive.get("color", "border_normal")))
    shadow_color = role_color(theme, str(shadow.get("color", "shadow")), "#000000")
    lines = [
        "# AUTO-GENERATED by Theme Studio. Edit the theme JSON through `theme`.",
        f"$bg = rgb({h(r['bg'])})",
        f"$bg_alt = rgb({h(r['bg_alt'])})",
        f"$fg = rgb({h(r['text'])})",
        f"$fg_dim = rgb({h(r['text_dim'])})",
        f"$accent = rgb({h(r['accent'])})",
        f"$accent2 = rgb({h(r['accent2'])})",
        f"$urgent = rgb({h(r['urgent'])})",
        "",
        f"$group_active = rgb({h(role_color(theme, str(groups.get('active', 'accent'))))})",
        f"$group_inactive = rgb({h(role_color(theme, str(groups.get('inactive', 'surface_1'))))})",
        f"$group_locked = rgb({h(role_color(theme, str(groups.get('locked', 'warning'))))})",
        f"$group_text = rgb({h(role_color(theme, str(groups.get('text', 'on_accent'))))})",
        "",
        "general {",
        f"    border_size = {int(w.get('border_width', 2))}",
        f"    gaps_in = {int(w.get('gaps_in', 5))}",
        f"    gaps_out = {int(w.get('gaps_out', 10))}",
    ]
    if active.get("style", "gradient") == "solid" or active_1 == active_2:
        lines.append(
            f"    col.active_border = {rgba(active_1, float(active.get('opacity', 1.0)))}"
        )
    else:
        lines.append(
            f"    col.active_border = {rgba(active_1, float(active.get('opacity', 1.0)))} "
            f"{rgba(active_2, float(active.get('opacity', 1.0)))} {int(active.get('angle', 45))}deg"
        )
    lines.extend(
        [
            f"    col.inactive_border = {rgba(inactive_color, float(inactive.get('opacity', 0.66)))}",
            "}",
            "",
            "decoration {",
            f"    rounding = {int(w.get('corner_radius', 10))}",
            f"    rounding_power = {float(w.get('rounding_power', 2.0))}",
            f"    active_opacity = {float(w.get('active_opacity', 1.0))}",
            f"    inactive_opacity = {float(w.get('inactive_opacity', 0.92))}",
            f"    dim_inactive = {'true' if float(w.get('inactive_dim', 0.08)) > 0 else 'false'}",
            f"    dim_strength = {float(w.get('inactive_dim', 0.08))}",
            "    blur {",
            f"        enabled = {'true' if blur.get('enabled', True) else 'false'}",
            f"        size = {int(blur.get('size', 8))}",
            f"        passes = {int(blur.get('passes', 3))}",
            f"        noise = {float(blur.get('noise', 0.0117))}",
            f"        contrast = {float(blur.get('contrast', 0.8916))}",
            f"        brightness = {float(blur.get('brightness', 0.8172))}",
            f"        vibrancy = {float(blur.get('vibrancy', 0.1696))}",
            "        new_optimizations = true",
            "        xray = false",
            "    }",
            "    shadow {",
            f"        enabled = {'true' if shadow.get('enabled', True) else 'false'}",
            f"        range = {int(shadow.get('radius', 20))}",
            f"        render_power = {int(shadow.get('render_power', 3))}",
            f"        offset = {shadow.get('offset', '0 0')}",
            f"        color = {rgba(shadow_color, float(shadow.get('opacity', 0.4)))}",
            "    }",
            "}",
        ]
    )
    if theme["components"]["waybar"].get("blur"):
        for namespace in ("waybar", "wofi", "rofi"):
            lines.extend(
                [
                    "",
                    "layerrule {",
                    f"    name = {namespace}-blur",
                    f"    match:namespace = {namespace}",
                    "    blur = yes",
                    "}",
                ]
            )
    animation = str(theme.get("style", {}).get("animation_preset", "smooth"))
    try:
        import theme_effects

        lines.extend(theme_effects.render_animations(animation, theme.get("style", {})))
    except ImportError:
        curves = {
            "subtle": "bezier = studio, 0.25, 0.1, 0.25, 1.0",
            "smooth": "bezier = studio, 0.16, 1, 0.3, 1",
            "snappy": "bezier = studio, 0.2, 0.8, 0.2, 1",
            "bouncy": "bezier = studio, 0.34, 1.56, 0.64, 1",
            "dramatic": "bezier = studio, 0.65, 0, 0.35, 1",
            "glitch": "bezier = studio, 0.8, -0.4, 0.2, 1.4",
        }
        lines.append("")
        if animation == "none":
            lines.extend(["animations {", "    enabled = false", "}"])
        else:
            lines.extend(
                [
                    curves.get(animation, curves["smooth"]),
                    "animations {",
                    "    enabled = true",
                    "    animation = windows, 1, 5, studio",
                    "    animation = border, 1, 6, studio",
                    "    animation = fade, 1, 5, studio",
                    "    animation = workspaces, 1, 5, studio",
                    "}",
                ]
            )
    return "\n".join(lines) + "\n"


@register(
    "windows",
    "Windows",
    "Hyprland gaps, borders, opacity, blur, shadows, and animations",
)
def apply_windows(theme: dict[str, Any]) -> list[Path]:
    path = CFG / "hypr" / "generated" / "theme.conf"
    atomic_text(path, render_hypr(theme))
    return [path]


@register("launcher", "Launcher", "Wofi and Rofi layout and state styling")
def apply_launcher(theme: dict[str, Any]) -> list[Path]:
    theme = ensure_theme_schema(theme)
    c = theme["components"]["launcher"]
    roles = theme["roles"]
    radius = int(c.get("radius", 10))
    border = int(c.get("border_width", 2))
    padding = int(c.get("padding", 10))
    width = int(c.get("width", 640))
    rows = int(c.get("rows", 8))
    bg = role_color(theme, str(c.get("background_role", "bg")))
    input_bg = role_color(theme, str(c.get("input_role", "bg_alt")))
    selected = role_color(theme, str(c.get("selected_role", "selected")))
    text = role_color(theme, str(c.get("text_role", "text")))
    paths: list[Path] = []
    wofi = CFG / "wofi" / "style.css"
    wofi_block = f"""#window {{
  background-color: {bg};
  color: {text};
  border: {border}px solid {roles["accent"]};
  border-radius: {radius}px;
  width: {width}px;
}}
#outer-box {{ padding: {padding}px; }}
#input {{ background: {input_bg}; color: {text}; padding: {max(4, padding - 2)}px; border-radius: {radius}px; }}
#entry {{ padding: {max(4, padding - 3)}px; border-radius: {radius}px; }}
#entry:selected {{ background: {selected}; color: {roles["on_accent"]}; }}"""
    replace_managed_block(wofi, "LAUNCHER", wofi_block, "/*")
    # Repair comment markers for CSS after generic insertion.
    css = (
        wofi.read_text(encoding="utf-8")
        .replace(
            "/* THEME-STUDIO-LAUNCHER-START\n", "/* THEME-STUDIO-LAUNCHER-START */\n"
        )
        .replace("/* THEME-STUDIO-LAUNCHER-END\n", "/* THEME-STUDIO-LAUNCHER-END */\n")
    )
    atomic_text(wofi, css)
    paths.append(wofi)
    rofi = CFG / "rofi" / "theme-engine.rasi"
    rofi_block = f"""window {{ width: {width}px; padding: {padding}px; border: {border}px; border-radius: {radius}px; }}
listview {{ lines: {rows}; }}
element {{ padding: {max(4, padding - 2)}px; border-radius: {radius}px; }}"""
    replace_managed_block(rofi, "LAUNCHER", rofi_block, "/*")
    rasi = (
        rofi.read_text(encoding="utf-8")
        .replace(
            "/* THEME-STUDIO-LAUNCHER-START\n", "/* THEME-STUDIO-LAUNCHER-START */\n"
        )
        .replace("/* THEME-STUDIO-LAUNCHER-END\n", "/* THEME-STUDIO-LAUNCHER-END */\n")
    )
    atomic_text(rofi, rasi)
    paths.append(rofi)
    return paths


