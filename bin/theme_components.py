@register("apps", "Apps", "Shared GTK, Qt, VS Code, and Firefox role overrides")
def apply_apps(theme: dict[str, Any]) -> list[Path]:
    theme = ensure_theme_schema(theme)
    c = theme["components"]["apps"]
    roles = theme["roles"]
    block = f"""/* Theme Studio app-state overrides */
@define-color studio_button {role_color(theme, str(c.get("button_role", "bg_alt")))};
@define-color studio_button_hover {role_color(theme, str(c.get("button_hover_role", "hover")))};
@define-color studio_selected {role_color(theme, str(c.get("selection_role", "selected")))};
@define-color studio_link {role_color(theme, str(c.get("link_role", "accent2")))};
@define-color studio_scrollbar {role_color(theme, str(c.get("scrollbar_role", "border_strong")))};
button {{ background-color: @studio_button; border-radius: {int(c.get("gtk_radius", 10))}px; }}
button:hover {{ background-color: @studio_button_hover; }}
selection, *:selected {{ background-color: @studio_selected; color: {roles["on_accent"]}; }}
*:link {{ color: @studio_link; }}
scrollbar slider {{ background-color: @studio_scrollbar; border-radius: {int(c.get("gtk_radius", 10))}px; }}"""
    paths = []
    for version in ("gtk-3.0", "gtk-4.0"):
        path = CFG / version / "gtk.css"
        replace_managed_block(path, "APPS", block, "/*")
        css = (
            path.read_text(encoding="utf-8")
            .replace("/* THEME-STUDIO-APPS-START\n", "/* THEME-STUDIO-APPS-START */\n")
            .replace("/* THEME-STUDIO-APPS-END\n", "/* THEME-STUDIO-APPS-END */\n")
        )
        atomic_text(path, css)
        paths.append(path)
    manifest = CFG / "theme-engine" / "apps-studio.json"
    atomic_text(manifest, json.dumps(c, indent=2) + "\n")
    paths.append(manifest)
    return paths


def apply_all(
    theme: dict[str, Any], names: list[str] | None = None
) -> dict[str, list[str]]:
    selected = (
        names
        if names is not None
        else [name for name in PLUGINS if name not in {"prompt", "windows"}]
    )
    results: dict[str, list[str]] = {}
    for name in selected:
        plugin = PLUGINS.get(name)
        if not plugin:
            continue
        try:
            results[name] = [str(path) for path in plugin.renderer(theme)]
        except (
            OSError,
            ValueError,
            TypeError,
            KeyError,
            RuntimeError,
            subprocess.SubprocessError,
        ) as exc:
            results[name] = [f"ERROR: {exc}"]
    _reload_components(selected)
    return results


def _reload_components(names: list[str]) -> None:
    def run(*cmd: str) -> None:
        try:
            subprocess.run(
                cmd,
                check=False,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=2,
            )
        except (FileNotFoundError, subprocess.TimeoutExpired):
            pass

    if "windows" in names:
        run("hyprctl", "reload")
    if "terminal" in names:
        run("pkill", "-USR1", "-x", "kitty")
    if "notifications" in names:
        try:
            dunst_running = (
                subprocess.run(
                    ["pgrep", "-x", "dunst"],
                    check=False,
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                    timeout=1,
                ).returncode
                == 0
            )
        except (FileNotFoundError, subprocess.TimeoutExpired):
            dunst_running = False
        if dunst_running:
            run("dunstctl", "reload")


def component_registry() -> list[dict[str, Any]]:
    result = []
    for name, plugin in PLUGINS.items():
        result.append(
            {
                "name": name,
                "label": plugin.label,
                "description": plugin.description,
                "fields": COMPONENT_FIELDS.get(name, ()),
            }
        )
    return result
